function fetchSVG(code) {
  return new Promise((resolve, reject) => {
    const url = `https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/${code}.svg`;
    https.get(url, (res) => {
      let data = '';
      res.on('data', (chunk) => { data += chunk; });
      res.on('end', () => {
        if (res.statusCode === 200) {
          resolve(data);
        } else {
          resolve(null);
        }
      });
    }).on('error', reject);
  });
}

function extractStrokes(svgContent) {
  if (!svgContent) return null;
  
  const strokes = [];
  const pathRegex = /<path[^>]*d="([^"]+)"[^>]*>/g;
  let match;
  
  while ((match = pathRegex.exec(svgContent)) !== null) {
    strokes.push(match[1]);
  }
  
  return strokes.length > 0 ? strokes : null;
}

async function main() {
  console.log('Fetching KanjiVG stroke data for kana...');
  const strokeData = {};
  let successCount = 0;
  let failCount = 0;
  
  for (const [char, code] of Object.entries(kanaList)) {
    process.stdout.write(`Fetching ${char} (${code})... `);
    try {
      const svg = await fetchSVG(code);
      const strokes = extractStrokes(svg);
      
      if (strokes) {
        strokeData[char] = strokes;
        console.log(`✓ (${strokes.length} strokes)`);
        successCount++;
      } else {
        console.log('✗ (no strokes found)');
        failCount++;
      }
      
      // Rate limiting
      await new Promise(resolve => setTimeout(resolve, 100));
    } catch (error) {
      console.log(`✗ (error: ${error.message})`);
      failCount++;
    }
  }
  
  console.log(`\nFetched: ${successCount} successful, ${failCount} failed`);
  
  // Generate TypeScript file
  const outputPath = path.join(__dirname, '..', 'src', 'data', 'strokeOrder.ts');
  const tsContent = `/**
 * KanjiVG stroke order data for Japanese kana
 * 
 * Source: KanjiVG (https://github.com/KanjiVG/kanjivg)
 * License: Creative Commons Attribution-Share Alike 3.0
 * 
 * Generated by scripts/fetch-kanjivg-kana.js
 */

export interface StrokeData {
  strokes: string[]; // SVG path data for each stroke
}

export const strokeOrderData: Record<string, StrokeData> = ${JSON.stringify(
  Object.entries(strokeData).reduce((acc, [char, strokes]) => {
    acc[char] = { strokes };
    return acc;
  }, {}),
  null,
  2
).replace(/"strokes":/g, 'strokes:')};

export function hasStrokeData(char: string): boolean {
  return char in strokeOrderData;
}

export function getStrokeCount(char: string): number {
  return strokeOrderData[char]?.strokes.length || 0;
}
`;
  
  fs.writeFileSync(outputPath, tsContent);
  console.log(`\nWrote stroke data to ${outputPath}`);
  console.log(`Total kana with stroke data: ${Object.keys(strokeData).length}`);
}

main().catch(console.error);
