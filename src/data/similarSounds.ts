/**
 * Get similar-sounding kana for distractors in listening quiz
 */
export function getSimilarKana(kana: string, isHiragana: boolean): string[] {
  const soundMap = isHiragana ? hiraganaSimilarSounds : katakanaSimilarSounds;
  return soundMap[kana] || [];
}
